// ---------- Date helpers ----------
const today = new Date();

// Relative date — n days from today at hh:mm
const dt = (daysFromToday, hour = 10, minute = 0) => {
    const d = new Date(today);
    d.setDate(d.getDate() + daysFromToday);
    d.setHours(hour, minute, 0, 0);
    return d.toISOString();
};

// Next occurrence of a weekday (0=Sun, 1=Mon, ..., 6=Sat) at hh:mm
const nextWeekday = (targetDay, hour = 10, minute = 0) => {
    const d = new Date();
    const diff = (targetDay + 7 - d.getDay()) % 7;
    d.setDate(d.getDate() + (diff === 0 ? 7 : diff));
    d.setHours(hour, minute, 0, 0);
    return d.toISOString();
};

// Absolute date — uses local time
const onDate = (yyyy, mm, dd, hh = 10, mi = 0) =>
    new Date(yyyy, mm - 1, dd, hh, mi, 0, 0).toISOString();

const addHours = (iso, hours) =>
    new Date(new Date(iso).getTime() + hours * 60 * 60 * 1000).toISOString();

